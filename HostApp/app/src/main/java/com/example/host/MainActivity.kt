package com.example.host

import android.os.Bundle
import android.util.Log
import android.widget.FrameLayout
import androidx.appcompat.app.AppCompatActivity
import com.callstack.reactnativebrownfield.ReactNativeFragment
import com.rnapp.ReactNativeHostManager // generated by create-react-native-brownfield

class MainActivity : AppCompatActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        // Docs, Android Integration step 10.
        ReactNativeHostManager.initialize(application) {
            Log.i("Host492", "JS bundle loaded")
        }

        val container = FrameLayout(this).apply { id = R.id.rn_container }
        setContentView(container)
        if (savedInstanceState == null) {
            supportFragmentManager.beginTransaction()
                .replace(R.id.rn_container, ReactNativeFragment.createReactNativeFragment("RnApp"))
                .commit()
        }
    }
}

package com.example.host

import android.graphics.Color
import android.os.Bundle
import android.util.Log
import android.util.TypedValue
import android.view.Gravity
import android.widget.Button
import android.widget.FrameLayout
import android.widget.LinearLayout
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import com.callstack.reactnativebrownfield.ReactNativeFragment
import com.rnapp.ReactNativeHostManager // generated by create-react-native-brownfield

/**
 * A plain native Android screen. React Native is started only when the
 * button is tapped, the way a brownfield app opens an RN screen on demand.
 */
class MainActivity : AppCompatActivity() {
    private lateinit var status: TextView
    private lateinit var openButton: Button

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        val root = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setBackgroundColor(Color.parseColor("#00695C"))
        }

        val header = TextView(this).apply {
            text = "Native host app (Kotlin)"
            setTextColor(Color.WHITE)
            setTextSize(TypedValue.COMPLEX_UNIT_SP, 22f)
            gravity = Gravity.CENTER
            setPadding(dp(16), dp(20), dp(16), dp(8))
        }
        status = TextView(this).apply {
            text = "React Native is not started yet."
            setTextColor(Color.parseColor("#B2DFDB"))
            setTextSize(TypedValue.COMPLEX_UNIT_SP, 16f)
            gravity = Gravity.CENTER
            setPadding(dp(16), 0, dp(16), dp(8))
        }
        openButton = Button(this).apply {
            text = "Open React Native"
            setOnClickListener { openReactNative() }
        }
        val buttonRow = FrameLayout(this).apply {
            setPadding(dp(16), 0, dp(16), dp(16))
            addView(openButton, FrameLayout.LayoutParams(
                FrameLayout.LayoutParams.WRAP_CONTENT,
                FrameLayout.LayoutParams.WRAP_CONTENT,
                Gravity.CENTER_HORIZONTAL,
            ))
        }
        // React Native is shown here, below the native header.
        val container = FrameLayout(this).apply {
            id = R.id.rn_container
            setBackgroundColor(Color.WHITE)
        }

        root.addView(header)
        root.addView(status)
        root.addView(buttonRow)
        root.addView(container, LinearLayout.LayoutParams(
            LinearLayout.LayoutParams.MATCH_PARENT, 0, 1f,
        ))
        setContentView(root)

        ViewCompat.setOnApplyWindowInsetsListener(root) { view, insets ->
            val bars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            view.setPadding(bars.left, bars.top, bars.right, bars.bottom)
            insets
        }
    }

    private fun openReactNative() {
        openButton.isEnabled = false
        status.text = "Starting React Native..."

        // Docs, Android Integration step 10. On `main` this call crashes.
        ReactNativeHostManager.initialize(application) {
            Log.i("Host492", "JS bundle loaded")
        }

        status.text = "React Native is running below."
        supportFragmentManager.beginTransaction()
            .replace(R.id.rn_container, ReactNativeFragment.createReactNativeFragment("RnApp"))
            .commit()
    }

    private fun dp(value: Int): Int =
        TypedValue.applyDimension(
            TypedValue.COMPLEX_UNIT_DIP, value.toFloat(), resources.displayMetrics,
        ).toInt()
}
